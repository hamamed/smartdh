// Routes that sit before everything else in the Express app.
import fs from "node:fs";
import path from "node:path";
import { UPLOAD_DIR } from "@/lib/config";
import { save } from "@/lib/db";
import { isLang } from "@/lib/locales";
import { pass, raw, redirect, referer } from "../ctx";
import type { Router } from "../router";

const MIME: Record<string, string> = {
  ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".gif": "image/gif",
  ".pdf": "application/pdf", ".txt": "text/plain; charset=utf-8", ".doc": "application/msword",
  ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document", ".apk": "application/vnd.android.package-archive",
};

/** A file from a folder that changes after the build (Next only serves public/ files present at build time). */
function serveFile(dir: string, name: string) {
  const safe = path.basename(name);
  const file = path.join(dir, safe);
  if (!safe || safe.startsWith(".") || !fs.existsSync(file) || !fs.statSync(file).isFile()) return null;
  return raw(fs.readFileSync(file), MIME[path.extname(safe).toLowerCase()] || "application/octet-stream",
    { headers: { "Cache-Control": "public, max-age=2592000" } });
}

export function registerSystemRoutes(r: Router): void {
  // In production nginx serves /uploads/ straight from disk; this covers running without it.
  r.get("/uploads/:file", (ctx) => serveFile(UPLOAD_DIR, ctx.params.file) || pass());
  r.get("/downloads/:file", (ctx) => serveFile(path.join(process.cwd(), "public", "downloads"), ctx.params.file) || pass());

  // Digital Asset Links for the Android TWA (generated by the build-apk workflow).
  r.get("/.well-known/assetlinks.json", () => {
    const f = path.join(process.cwd(), "public", ".well-known", "assetlinks.json");
    if (fs.existsSync(f)) return raw(fs.readFileSync(f), "application/json");
    return raw("[]", "application/json; charset=utf-8");
  });

  r.get("/lang/:code", (ctx) => {
    const code = ctx.params.code;
    if (isLang(code)) {
      ctx.session.lang = code;
      // Remember it on the account too, so their emails go out in this language.
      if (ctx.user && ctx.user.lang !== code) {
        ctx.user.lang = code;
        save(ctx.db);
      }
    }
    const back = referer(ctx);
    return redirect(back && !back.includes("/lang/") ? back : "/");
  });
}
